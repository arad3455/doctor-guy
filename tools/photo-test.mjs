// Photo mode: P opens it (HUD hidden, world frozen), drag orbits, a filter applies, Save makes a PNG; ambience runs.
import puppeteer from 'puppeteer-core';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new', args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader', '--autoplay-policy=no-user-gesture-required'], defaultViewport: { width: 1280, height: 720 }, protocolTimeout: 600000 });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto(process.env.BASE ?? 'http://localhost:8765/', { waitUntil: 'domcontentloaded', timeout: 180000 });
await page.waitForFunction(() => !document.getElementById('start').disabled, { timeout: 300000, polling: 1000 });
await page.click('#start');
const g = (fn, a) => page.evaluate(fn, a);
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const frames = () => g(() => new Promise((res) => { let n = 0; const f = () => (++n >= 3 ? res() : requestAnimationFrame(f)); requestAnimationFrame(f); }));
const r = {};
await g(() => { __game.player.pos.set(122, 0, 86); });
await frames();
await page.keyboard.press('KeyP');
await frames();
r.open = await g(() => __game.photo.active && !document.getElementById('photo').classList.contains('hidden'));
r.hudHidden = await g(() => getComputedStyle(document.getElementById('hud')).display === 'none' || document.getElementById('hud').classList.contains('hidden'));
const t0 = await g(() => __game.missions.time);
await page.mouse.move(640, 360); await page.mouse.down(); await page.mouse.move(420, 300, { steps: 6 }); await page.mouse.up();
await page.click('#photo [data-f="1"]');
await frames(); await frames();
r.frozen = (await g(() => __game.missions.time)) === t0;
r.filter = await g(() => __game.renderer.domElement.style.filter);
await page.screenshot({ path: '.shots/photo-1-mode.png' });
const client = await page.target().createCDPSession();
await client.send('Browser.setDownloadBehavior', { behavior: 'deny' }).catch(() => {});
await page.click('#photo .ph-snap');
await wait(1500);
r.snap = await g(() => __game.photo.lastSnap);
await page.keyboard.press('Escape');
await frames();
r.closed = await g(() => !__game.photo.active && __game.renderer.domElement.style.filter === '');
r.ambience = await g(() => ({ ready: __game.ambience?.ready ?? 'n/a' }));
console.log(JSON.stringify(r, null, 1));
console.log('ERRORS:', errors.length ? errors : 'none');
await browser.close();
